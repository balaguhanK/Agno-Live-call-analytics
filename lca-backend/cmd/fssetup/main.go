// Command fssetup configures a local FreeSWITCH for the dashboard's browser
// phone: a SIP account per agent, the support number that rings agents, the
// LAN address for media, and a locked-down Event Socket.
//
//	go run ./cmd/fssetup            # write files to freeswitch/staged for review
//	go run ./cmd/fssetup -apply     # back up and install them, then reload (run as Administrator)
package main

import (
	"context"
	"errors"
	"flag"
	"fmt"
	"io/fs"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"time"

	"lca-backend/internal/config"
	"lca-backend/internal/esl"
	"lca-backend/internal/phone"
	"lca-backend/internal/srs"
)

const (
	eslTimeout = 5 * time.Second
	// FreeSWITCH's factory event socket password, tried if ours isn't set yet
	defaultESLPassword = "ClueCon"
	agentFilePrefix    = "lca_agent_"
	// How long customers ring before hearing "no answer"
	ringSeconds = 60
)

var agentIDPattern = regexp.MustCompile(`^[A-Za-z0-9_.-]{1,64}$`)

func main() {
	confDir := flag.String("conf", `C:\Program Files\FreeSWITCH\conf`, "FreeSWITCH conf directory")
	staged := flag.String("staged", filepath.Join("freeswitch", "staged"), "where to write files for review")
	apply := flag.Bool("apply", false, "install the files into the conf directory (needs Administrator) and reload FreeSWITCH")
	agentsFlag := flag.String("agents", "", "comma-separated agent IDs (default: ask the backend)")
	flag.Parse()

	if err := run(*confDir, *staged, *apply, *agentsFlag); err != nil {
		fmt.Fprintln(os.Stderr, "error:", err)
		os.Exit(1)
	}
}

func run(confDir, stagedDir string, apply bool, agentsFlag string) error {
	cfg, err := config.Load()
	if err != nil {
		return err
	}
	eslPassword := os.Getenv("FREESWITCH_ESL_PASSWORD")
	switch {
	case cfg.Phone.Secret == "":
		return errors.New("set FS_SIP_SECRET in .env (a long random string)")
	case len(eslPassword) < 12:
		return errors.New("set FREESWITCH_ESL_PASSWORD in .env to at least 12 characters")
	}

	agents, err := agentList(cfg, agentsFlag)
	if err != nil {
		return err
	}
	fmt.Println("agents:", strings.Join(agents, ", "))

	files, err := buildFiles(confDir, agents, cfg.Phone, eslPassword)
	if err != nil {
		return err
	}
	stale, err := staleAgentFiles(confDir, files)
	if err != nil {
		return err
	}

	for rel, content := range files {
		path := filepath.Join(stagedDir, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
			return err
		}
	}
	fmt.Printf("wrote %d files to %s for review\n", len(files), stagedDir)
	if !apply {
		fmt.Println("run again with -apply in an Administrator terminal to install them")
		return nil
	}

	backup := filepath.Join(confDir, "lca-backup-"+time.Now().Format("20060102-150405"))
	for rel, content := range files {
		if err := install(confDir, backup, rel, []byte(content)); err != nil {
			if errors.Is(err, fs.ErrPermission) {
				return fmt.Errorf("%w\nopen PowerShell as Administrator and run the command again", err)
			}
			return err
		}
	}
	for _, rel := range stale {
		if err := backupFile(confDir, backup, rel); err != nil {
			return err
		}
		if err := os.Remove(filepath.Join(confDir, rel)); err != nil {
			return err
		}
		fmt.Println("removed old agent account", rel)
	}
	fmt.Println("installed; originals backed up to", backup)
	return reload(eslPassword)
}

// agentList returns the agents to create SIP accounts for.
func agentList(cfg config.Config, flagValue string) ([]string, error) {
	var agents []string
	if flagValue != "" {
		agents = strings.Split(flagValue, ",")
	} else {
		b := &srs.Backend{BaseURL: getenv("BACKEND_URL", "http://localhost:"+cfg.Port), Token: cfg.IngestToken, HTTP: &http.Client{Timeout: eslTimeout}}
		var err error
		agents, err = b.Agents(context.Background())
		if err != nil {
			return nil, fmt.Errorf("couldn't get agents from the backend (is it running?): %w\nor pass -agents BobS,BabuS", err)
		}
	}
	out := agents[:0]
	for _, a := range agents {
		a = strings.TrimSpace(a)
		if !agentIDPattern.MatchString(a) {
			return nil, fmt.Errorf("agent ID %q can't be a SIP user (letters, digits, . _ - only)", a)
		}
		out = append(out, a)
	}
	if len(out) == 0 {
		return nil, errors.New("no agents to set up")
	}
	return out, nil
}

// buildFiles returns conf-relative paths and their new contents.
func buildFiles(confDir string, agents []string, ph phone.Config, eslPassword string) (map[string]string, error) {
	files := map[string]string{}

	for _, a := range agents {
		files[filepath.Join("directory", "default", agentFilePrefix+a+".xml")] = fmt.Sprintf(`<include>
  <!-- Generated by lca-backend fssetup for dashboard agent %[1]s; regenerate instead of editing -->
  <user id="%[1]s">
    <params>
      <param name="password" value="%[2]s"/>
    </params>
    <variables>
      <variable name="user_context" value="default"/>
      <variable name="effective_caller_id_name" value="%[1]s"/>
      <variable name="effective_caller_id_number" value="%[1]s"/>
    </variables>
  </user>
</include>
`, a, phone.Password(ph.Secret, a))
	}

	targets := make([]string, len(agents))
	for i, a := range agents {
		targets[i] = "user/" + a + "@${domain_name}"
	}
	files[filepath.Join("dialplan", "default", "cx_support.xml")] = fmt.Sprintf(`<include>
  <!-- Generated by lca-backend fssetup. Dial "support" or %[1]s to ring every online
       dashboard agent at once (their browser phones); the first to answer gets the call. -->
  <extension name="cx_support">
    <condition field="destination_number" expression="^(support|%[1]s)$">
      <action application="set" data="ringback=${us-ring}"/>
      <action application="set" data="call_timeout=%[2]d"/>
      <action application="set" data="continue_on_fail=true"/>
      <action application="set" data="hangup_after_bridge=true"/>
      <action application="bridge" data="{ignore_early_media=true}%[3]s"/>
      <action application="answer"/>
      <action application="playback" data="ivr/ivr-no_user_response.wav"/>
      <action application="hangup" data="NO_ANSWER"/>
    </condition>
  </extension>
</include>
`, ph.QueueNumber, ringSeconds, strings.Join(targets, ","))

	// Advertise the LAN address, not a STUN-discovered public one, so browsers
	// and softphones on this network can reach FreeSWITCH's media
	internal, err := os.ReadFile(filepath.Join(confDir, "sip_profiles", "internal.xml"))
	if err != nil {
		return nil, err
	}
	profile := string(internal)
	for _, name := range []string{"ext-rtp-ip", "ext-sip-ip"} {
		re := regexp.MustCompile(`<param name="` + name + `" value="[^"]*"/>`)
		if !re.MatchString(profile) {
			return nil, fmt.Errorf("internal.xml has no %s param to update", name)
		}
		// Literal: $${...} is FreeSWITCH syntax, not a regexp group
		profile = re.ReplaceAllLiteralString(profile, `<param name="`+name+`" value="$${local_ip_v4}"/>`)
	}
	// Browser phones offer their LAN address for WebRTC media. Without a
	// candidate ACL FreeSWITCH only accepts public (wan) addresses, rejects
	// the LAN one and drops the answered call as INCOMPATIBLE_DESTINATION.
	if !strings.Contains(profile, `name="apply-candidate-acl"`) {
		wsLine := regexp.MustCompile(`(?m)^(\s*)<param name="ws-binding"[^>]*/>\s*$`)
		loc := wsLine.FindStringSubmatchIndex(profile)
		if loc == nil {
			return nil, errors.New("internal.xml has no ws-binding param to add WebRTC settings after")
		}
		indent := profile[loc[2]:loc[3]]
		var acl strings.Builder
		for _, list := range []string{"localnet.auto", "rfc1918.auto", "wan.auto"} {
			acl.WriteString("\n" + indent + `<param name="apply-candidate-acl" value="` + list + `"/>`)
		}
		profile = profile[:loc[1]] + acl.String() + profile[loc[1]:]
	}
	files[filepath.Join("sip_profiles", "internal.xml")] = profile

	files[filepath.Join("autoload_configs", "event_socket.conf.xml")] = fmt.Sprintf(`<configuration name="event_socket.conf" description="Socket Client">
  <!-- Generated by lca-backend fssetup: only this computer may connect -->
  <settings>
    <param name="nat-map" value="false"/>
    <param name="listen-ip" value="127.0.0.1"/>
    <param name="listen-port" value="8021"/>
    <param name="password" value="%s"/>
    <param name="apply-inbound-acl" value="loopback.auto"/>
  </settings>
</configuration>
`, xmlAttr(eslPassword))
	return files, nil
}

func xmlAttr(s string) string {
	return strings.NewReplacer("&", "&amp;", `"`, "&quot;", "<", "&lt;", ">", "&gt;").Replace(s)
}

// staleAgentFiles lists agent accounts from an earlier run that are no longer agents.
func staleAgentFiles(confDir string, files map[string]string) ([]string, error) {
	matches, err := filepath.Glob(filepath.Join(confDir, "directory", "default", agentFilePrefix+"*.xml"))
	if err != nil {
		return nil, err
	}
	var stale []string
	for _, m := range matches {
		rel, _ := filepath.Rel(confDir, m)
		if _, keep := files[rel]; !keep {
			stale = append(stale, rel)
		}
	}
	return stale, nil
}

func backupFile(confDir, backup, rel string) error {
	data, err := os.ReadFile(filepath.Join(confDir, rel))
	if errors.Is(err, fs.ErrNotExist) {
		return nil
	}
	if err != nil {
		return err
	}
	dst := filepath.Join(backup, rel)
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	return os.WriteFile(dst, data, 0o600)
}

func install(confDir, backup, rel string, content []byte) error {
	if err := backupFile(confDir, backup, rel); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(confDir, rel), content, 0o644)
}

// reload applies the new configuration without restarting FreeSWITCH.
func reload(eslPassword string) error {
	var conn *esl.Conn
	var err error
	for _, pw := range []string{eslPassword, defaultESLPassword} {
		if conn, err = esl.Dial("127.0.0.1:8021", pw, eslTimeout); err == nil {
			break
		}
	}
	if err != nil {
		return fmt.Errorf("files installed, but FreeSWITCH couldn't be reached to reload (%w); restart FreeSWITCH instead", err)
	}
	defer conn.Close()
	for _, cmd := range []string{"reloadxml", "sofia profile internal restart"} {
		out, err := conn.API(cmd, 30*time.Second)
		if err != nil {
			return fmt.Errorf("%s: %w", cmd, err)
		}
		fmt.Printf("%s: %s\n", cmd, firstLine(out))
	}
	// Last: this drops our own connection while the event socket restarts
	_, _ = conn.API("reload mod_event_socket", eslTimeout)
	fmt.Println("event socket reloaded (localhost only, new password)")
	return nil
}

func firstLine(s string) string {
	line, _, _ := strings.Cut(s, "\n")
	return line
}

func getenv(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}
